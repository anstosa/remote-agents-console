import { execFileSync } from 'node:child_process';
import { existsSync } from 'node:fs';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { NewTaskService } from '../src/new-task/service.js';
import { testConfig, testWorktree } from './helpers/config.js';

const worktree = testWorktree({ id: 'proj:/worktrees/cora', projectId: 'proj', label: 'Cora', path: '/worktrees/cora', hostPath: '/home/ubuntu/cora', pinned: false, newTask: 'detach && new {taskId}' });
const config = testConfig();
const agent = { id: 'agent-1', pane: { paneId: '%1', sessionId: '$1', socketFingerprint: 'socket' }, home: worktree.identity, title: 'Ready' };
const socket = { fingerprint: 'socket', path: '/tmp/tmux', device: 1, inode: 2 };
const discoveryStub = () => ({ target: async () => ({ agent, socket }), worktreesNow: () => [worktree] });

const cleanCommand = async (_binary: string, args: string[]) => ({ code: 0, stdout: args.includes('status') ? '' : args.includes('rev-list') ? '0\t0\n' : 'origin/main\n' });

const homes: string[] = [];

// remove only isolated shell fixtures and restore runtime settings
afterEach(async () => {
  await Promise.all(homes.splice(0).map(home => rm(home, { recursive: true, force: true })));
  vi.unstubAllEnvs();
});

describe('new task', () => {
  // exercise each supported user shell without loading operator startup files
  for (const [name, candidates, rc] of [
    ['bash', ['/bin/bash'], '.bashrc'],
    ['zsh', ['/usr/bin/zsh', '/home/linuxbrew/.linuxbrew/bin/zsh'], '.zshrc'],
    ['fish', ['/usr/bin/fish', '/usr/local/bin/fish', '/home/linuxbrew/.linuxbrew/bin/fish'], '.config/fish/config.fish']
  ] as const) {
    // select an installed shell without changing the operator's configuration
    const shell = candidates.find(candidate => existsSync(candidate));
    // run the actual tmux launch argv with harmless aliases and a shell function
    it.skipIf(shell === undefined)(`runs new tasks with ${name} aliases and functions, then leaves a shell open`, async () => {
      const root = await mkdtemp(join(tmpdir(), 'rac-new-task-shell-'));
      homes.push(root);
      const home = join(root, "user's home");
      const path = join(home, "worktree's folder");
      await mkdir(path, { recursive: true });
      await mkdir(join(home, '.config/fish'), { recursive: true });
      // keep distribution login hints out of the captured task output
      await writeFile(join(home, '.hushlogin'), '');
      await writeFile(join(home, '.zshenv'), 'skip_global_compinit=1\n');
      const absentCommand = name === 'fish' ? '(set -q RAC_AGENT_COMMAND; and echo set; or echo unset)' : '"${RAC_AGENT_COMMAND-unset}"';
      const nativePath = name === 'fish' ? '(string join ":" $PATH)' : '"$PATH"';
      const functionBody = name === 'fish'
        ? `function task_function\nprintf '%s|%s|%s|%s|%s\\n' $argv[1] "$PWD" "$HOME" ${nativePath} ${absentCommand}\nend\n`
        : `task_function() { printf '%s|%s|%s|%s|%s\\n' "$1" "$PWD" "$HOME" ${nativePath} ${absentCommand}; }\n`;
      await writeFile(join(home, rc), `alias detach='printf "%s\\n" detached'\nalias new=task_function\n${functionBody}`);
      const hostBridge = name !== 'bash';
      vi.stubEnv('RAC_INTERACTIVE_SHELL', hostBridge ? '/test/native/bash' : shell!);
      vi.stubEnv('RAC_HOST_INTERACTIVE_SHELL', hostBridge ? shell! : '/test/host/zsh');
      // execute the bridge branch only where its configured shell is installed
      vi.stubEnv('RAC_HOST_TMUX_DIR', hostBridge ? root : undefined);
      const hostPath = `${join(home, 'host bin')}:/usr/bin:/bin`;
      vi.stubEnv('RAC_HOST_PATH', hostPath);
      const place = { ...worktree, path, identity: path, hostPath: path, newTask: "detach && new '{taskId}'" };
      const discovery = { target: async () => ({ agent: { ...agent, home: path }, socket }), worktreesNow: () => [place] };
      let output = '';
      // execute only the new pane shell while keeping Git and tmux mutations mocked
      const command = async (binary: string, args: string[]) => {
        // provide the current session identity during replacement
        if (args.includes('display-message')) return { code: 0, stdout: args.at(-1) === '#{session_id}' ? '$1\n' : 'old-session\n' };
        // use the exact shell argv generated by the service
        if (args.includes('new-session')) {
          const shellIndex = args.indexOf(shell!);
          expect(shellIndex).toBeGreaterThan(0);
          output = execFileSync(shell!, args.slice(shellIndex + 1), {
            cwd: path,
            env: { HOME: home, ZDOTDIR: home, XDG_CONFIG_HOME: join(home, '.config'), PATH: '/usr/bin:/bin', TERM: 'dumb' },
            input: `printf 'resumed:%s\\n' ${absentCommand}\nexit\n`,
            encoding: 'utf8', stdio: ['pipe', 'pipe', 'ignore'], timeout: 5_000
          });
          return { code: 0, stdout: '%7\n' };
        }
        return cleanCommand(binary, args);
      };
      const tmux = { closeSession: async () => true, markSessionPlace: async () => true };
      const service = new NewTaskService(config, discovery as never, tmux as never, command);
      await expect(service.start(agent.id)).resolves.toBe(true);
      expect(output).toMatch(/^detached\n[A-Za-z0-9_-]{8}\|/u);
      expect(output).toContain(`|${path}|${home}|${hostPath}|unset\n`);
      expect(output).toContain('resumed:unset\n');
    }, 10_000);
  }

  // select either shell source without spawning a fake executable
  for (const [name, hostBridge, expectedShell] of [
    ['native', false, '/test/native/bash'],
    ['host', true, '/test/host/zsh']
  ] as const) {
    // inspect the selected launch vector through the injected tmux seam
    it(`selects the configured ${name} interactive shell`, async () => {
      vi.stubEnv('RAC_INTERACTIVE_SHELL', '/test/native/bash');
      vi.stubEnv('RAC_HOST_INTERACTIVE_SHELL', '/test/host/zsh');
      vi.stubEnv('RAC_HOST_TMUX_DIR', hostBridge ? '/host-tmux' : undefined);
      const calls: string[][] = [];
      // capture argv but do not execute the selected shell
      const command = async (_binary: string, args: string[]) => {
        calls.push(args);
        if (args.includes('display-message')) return { code: 0, stdout: args.at(-1) === '#{session_id}' ? '$1\n' : 'old-session\n' };
        if (args.includes('new-session')) return { code: 0, stdout: '%7\n' };
        return cleanCommand(_binary, args);
      };
      const tmux = { closeSession: async () => true, markSessionPlace: async () => true };
      const service = new NewTaskService(config, discoveryStub() as never, tmux as never, command);
      await expect(service.start(agent.id)).resolves.toBe(true);
      const launch = calls.find(args => args.includes('new-session'));
      expect(launch).toBeDefined();
      expect(launch!.at(-3)).toBe(expectedShell);
      expect(launch!.at(-1)).toContain(expectedShell);
    });
  }

  it('closes the agent and starts the configured task in a new tmux session', async () => {
    const discovery = discoveryStub();
    const calls: string[] = [];
    const tmux = { closeSession: async () => { calls.push('close-session'); return true; }, markSessionPlace: async (_socket: unknown, pane: string, placeId: string) => { calls.push(`mark ${pane} ${placeId}`); return true; } };
    const command = async (binary: string, args: string[]) => {
      calls.push(`${binary} ${args.join(' ')}`);
      // return the requested stable session field
      if (args.includes('display-message')) return { code: 0, stdout: args.at(-1) === '#{session_id}' ? '$1\n' : 'cora\n' };
      if (args.includes('new-session')) return { code: 0, stdout: '%7\n' };
      return cleanCommand(binary, args);
    };
    const service = new NewTaskService(config, discovery as never, tmux as never, command);

    await expect(service.available(agent.id)).resolves.toEqual({ enabled: true });
    await expect(service.start(agent.id)).resolves.toBe(true);
    expect(calls).toContain('close-session');
    expect(calls.some(call => /rename-session .* rac-replacing-/u.test(call))).toBe(true);
    const launch = calls.find(call => call.includes('new-session'));
    expect(launch).toContain('new-session -d -s cora -P -F #{pane_id} -c /home/ubuntu/cora');
    // the new session replaces the Agent's as the Worktree's Workspace, marked through its pane
    expect(calls).toContain(`mark %7 ${worktree.id}`);
    expect(launch).toContain('RAC_AGENT_COMMAND=');
    expect(launch).toMatch(/cd -- '\\''\/home\/ubuntu\/cora'\\'' && eval '\\''detach && new [A-Za-z0-9_-]{8}'\\''/);
    expect(calls.findIndex(call => call.includes('new-session'))).toBeLessThan(calls.indexOf('close-session'));
  });

  it('does not suspend an agent while the worktree has uncommitted work', async () => {
    const discovery = discoveryStub();
    const tmux = { closeSession: async () => true, markSessionPlace: async () => true };
    const dirtyCommand = async (_binary: string, args: string[]) => ({ code: 0, stdout: args.includes('status') ? ' M README.md\n' : 'origin/main\n' });
    const service = new NewTaskService(config, discovery as never, tmux as never, dirtyCommand);

    await expect(service.available(agent.id)).resolves.toEqual({ enabled: false, reason: 'The working copy must be clean, and any checked-out branch must be pushed before starting a new task.' });
    await expect(service.start(agent.id)).resolves.toBe(false);
  });

  it('allows a clean detached checkout to start a new task', async () => {
    const discovery = discoveryStub();
    const tmux = { closeSession: async () => true, markSessionPlace: async () => true };
    const detachedCommand = async (_binary: string, args: string[]) => ({ code: args.includes('rev-parse') || args.includes('symbolic-ref') ? 1 : 0, stdout: '' });
    const service = new NewTaskService(config, discovery as never, tmux as never, detachedCommand);

    await expect(service.available(agent.id)).resolves.toEqual({ enabled: true });
    await expect(service.start(agent.id)).resolves.toBe(true);
  });

  it('allows a clean branch whose configured upstream is gone to start a new task', async () => {
    const discovery = discoveryStub();
    const tmux = { closeSession: async () => true, markSessionPlace: async () => true };
    const goneUpstreamCommand = async (_binary: string, args: string[]) => {
      if (args.includes('status')) return { code: 0, stdout: '' };
      if (args.includes('symbolic-ref')) return { code: 0, stdout: 'refs/heads/feature/merged\n' };
      if (args.includes('--contains=HEAD')) return { code: 0, stdout: '' };
      if (args.includes('--format=%(upstream:track)')) return { code: 0, stdout: '[gone]\n' };
      return { code: 0, stdout: '' };
    };
    const service = new NewTaskService(config, discovery as never, tmux as never, goneUpstreamCommand);

    await expect(service.available(agent.id)).resolves.toEqual({ enabled: true });
    await expect(service.start(agent.id)).resolves.toBe(true);
  });
});
